def vivado_detail(x):
    """Global Vivado flow, steps of FINN's MakeZYNQProject (impl_1 command times)."""
    T = os.path.join(SCALE, "clk10", "vshell_timing")
    name = "vgg10_s%g%s" % (x["factor"], x["mode"])
    r = [json.loads(line) for line in open(os.path.join(T, "runs.jsonl")) if line.strip()]
    r = [e for e in r if e["model"] == name and e["mode"] == "vivado"][-1]
    proj = os.path.dirname(r["route_rpt"])
    runs = os.path.join(proj, "finn_zynq_link.runs")
    dur = {}
    for d in os.listdir(runs):
        b, e = os.path.join(runs, d, ".vivado.begin.rst"), os.path.join(runs, d, ".vivado.end.rst")
        if os.path.isfile(e):
            dur[d] = os.path.getmtime(e) - os.path.getmtime(b)
    acc = dur["top_StreamingDataflowPartition_1_0_synth_1"]
    shell = max(v for k, v in dur.items() if k.startswith("top_") and "StreamingDataflow" not in k)
    impl, top = dur["impl_1"], dur["synth_1"]
    log = open(os.path.join(runs, "impl_1", "runme.log")).read()
    cmd = {}
    for c, t in re.findall(r"^(\w+): Time \(s\): cpu = [\d:]+ ; elapsed = ([\d:.]+)", log, re.M):
        h, m, s = t.split(":")
        cmd[c] = cmd.get(c, 0) + int(h) * 3600 + int(m) * 60 + float(s)
    be = json.load(open(os.path.join(T, name + "_vivado", "bitfile_experiment.json")))
    st = {}
    for s in be["stages"]:
        st[s["stage"]] = st.get(s["stage"], 0) + s["s"]
    mz = st["MakeZYNQProject"]
    core = ["link_design", "opt_design", "place_design", "phys_opt_design", "route_design", "write_bitstream", "write_checkpoint"]
    return {
        "total": r["wall_s"],
        "prep": r["wall_s"] - mz,
        "bd": mz - max(acc, shell) - top - impl,
        "acc": acc,
        "shell": shell,
        "ipsynth": max(acc, shell),
        "top": top,
        "link": cmd.get("link_design", 0),
        "opt": cmd.get("opt_design", 0),
        "place": cmd.get("place_design", 0),
        "physopt": cmd.get("phys_opt_design", 0),
        "route": cmd.get("route_design", 0),
        "bit": cmd.get("write_bitstream", 0),
        "ckpt": cmd.get("write_checkpoint", 0),
        "rep": impl - sum(cmd.get(k, 0) for k in core),
    }


def island_detail(x):
    T = os.path.join(SCALE, "clk10", "vshell_timing")
    name = "vgg10_s%g%s" % (x["factor"], x["mode"])
    r = [json.loads(line) for line in open(os.path.join(T, "runs.jsonl")) if line.strip()]
    r = [e for e in r if e["model"] == name and e["mode"] == "islands"][-1]
    j = json.load(open(os.path.join(T, name + "_islands", "islands", "rwislands_zynq.json")))
    st, a, ss = j["stamps"], j["assembly_stamps"], j["stitch_stamps"]
    isl = max(j["islands"].values(), key=lambda v: v.get("pnr_s", 0))
    s = isl["stamps"]
    prev, steps = 0.0, {}
    for k in ("link", "opt", "place", "phys_opt", "route", "write"):
        steps[k] = s.get(k, prev) - prev
        prev = s.get(k, prev)
    return {
        "total": r["wall_s"],
        "prep": r["wall_s"] - j["total_s"],
        "synth": st["synth"],
        "largest": max(v.get("synth_s", 0) for v in j["synth"].values()),
        "nodes": len(j["synth"]),
        "floorplan": st["floorplan"] - st["shell"],
        "islands": st["islands"] - st["floorplan"],
        "n_isl": len(j["islands"]),
        "isl_place": steps["place"],
        "isl_route": steps["route"],
        "isl_other": isl["pnr_s"] - steps["place"] - steps["route"],
        "stitch": st["stitch"] - st["islands"],
        "read": a["read_accel"],
        "aroute": a["route"] - a["read_accel"],
        "bit": a["bitstream"] - a["route"],
        "rep": a["reports"] - a["bitstream"],
    }


