def stamps(log):
    return {k: float(v) for k, v in re.findall(r"^STAMP (\w+) ([\d.]+)", open(log).read(), re.M)}


def asm_case(label, run_dir):
    j = json.load(open(os.path.join(run_dir, "rwislands_zynq.json")))
    a = j["assembly_stamps"]
    st = j["stamps"]
    return {
        "label": label,
        "stitch": st["stitch"] - st["islands"],
        "open": a["open_shell"],
        "open_hidden": True,
        "read": a["read_accel"],
        "route": a["route"] - a["read_accel"],
        "bit": a["bitstream"] - a.get("post_route_phys_opt", a["route"]),
        "rep": a["reports"] - a["bitstream"],
        "log": os.path.join(run_dir, "assembly", "assemble.log"),
    }


def route_phases(log):
    t = open(log).read()
    r = t[t.index("Command: route_design"):]
    r = r[: r.index("route_design: Time") + 200]

    def el(s):
        h, m, x = s.split(":")
        return int(h) * 3600 + int(m) * 60 + float(x)

    ph, last = {}, 0.0
    for name, blk in re.findall(r"^(Phase \d+ [^\n|]+?)\n(.*?)(?=^Phase \d+ [^|\n]+\n|\Z)", r, re.M | re.S):
        m = re.findall(r"elapsed = ([\d:.]+)", blk)
        if m:
            e = el(m[-1])
            ph[re.sub(r"^Phase \d+ ", "", name.strip())] = e - last
            last = e
    total = el(re.search(r"route_design: Time.*?elapsed = ([\d:.]+)", r).group(1))
    failed = int(re.search(r"Number of Failed Nets\s+=\s+(\d+)", r).group(1))
    rs = open(log.replace("assemble.log", "route_status.rpt")).read()
    routable = int(re.search(r"# of routable nets\.+ :\s+(\d+)", rs).group(1))
    return ph, total, failed, routable


