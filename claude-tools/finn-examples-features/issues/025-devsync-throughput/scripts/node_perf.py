"""Single-node stitched-IP rtlsim throughput (behav=False) using the node IP already
generated by a build. Input always valid, output always ready, so the measured
interval is the node's own steady-state rate.

usage: python node_perf.py <model.onnx> <tag> <node,node,...|all> <N>
"""
import copy
import json
import os
import sys
from onnx import helper
from qonnx.core.modelwrapper import ModelWrapper

from finn.transformation.fpgadataflow.create_stitched_ip import CreateStitchedIP
from finn.transformation.fpgadataflow.set_fifo_depths import xsi_fifosim
from finn.util.rtlsim import annotate_rtlsim_performance

PART = "xczu3eg-sfvc784-2-e"
CLK = 10.0
src, tag, names, N = sys.argv[1], sys.argv[2], sys.argv[3], int(sys.argv[4])
out_dir = os.path.join(os.environ["FINN_BUILD_DIR"], "results")
os.makedirs(out_dir, exist_ok=True)
m = ModelWrapper(src)
nodes = [n for n in m.graph.node if not n.op_type.startswith("StreamingFIFO")]
if names != "all":
    nodes = [n for n in nodes if n.name in names.split(",")]
init_names = {i.name for i in m.graph.initializer}


def vi(name):
    shape = m.get_tensor_shape(name)
    return helper.make_tensor_value_info(name, 1, shape)


res = {}
for n in nodes:
    ins = [i for i in n.input if i not in init_names and i != ""]
    inits = [copy.deepcopy(i) for i in m.graph.initializer if i.name in n.input]
    g = helper.make_graph(
        [copy.deepcopy(n)], "single_" + n.name, [vi(ins[0])], [vi(n.output[0])], inits
    )
    sm = m.make_subgraph_modelwrapper(g)
    for t in list(n.input) + list(n.output):
        if t:
            sm.set_tensor_datatype(t, m.get_tensor_datatype(t))
    sm = sm.transform(CreateStitchedIP(PART, CLK))
    d = xsi_fifosim(sm, N, max_iters=100000, behav=False)
    d = {k: v for k, v in d.items() if "max_count" not in k}
    d = annotate_rtlsim_performance(d, N, CLK)
    avg = d["steady_state_cycles"] / max(1, d["steady_state_frames"])
    from qonnx.custom_op.registry import getCustomOp

    est = getCustomOp(n).get_exp_cycles()
    print("RESULT", tag, n.name, "N=%d" % N, "est=", est, "interval(last)=",
          d["interval_cycles"], "avg_steady=", round(avg, 3), "latency=", d["latency_cycles"])
    res[n.name] = dict(est=est, avg_steady=avg, **d)
with open(os.path.join(out_dir, tag + "_nodes.json"), "w") as f:
    json.dump(res, f, indent=2)
